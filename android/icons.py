def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["generate", "check", "scan", "sheet"])
    parser.add_argument("--project", required=True)
    parser.add_argument("--turn-root", required=True)
    parser.add_argument("--package", default="com.sendaturn.app")
    parser.add_argument("--commit", help="scan: the iOS commit (default: icons.toml's ios_commit)")
    parser.add_argument("--out", help="sheet: the output folder")
    args = parser.parse_args(argv)
    project = Project(args)
    try:
        if args.command == "generate":
            do_generate(project)
        elif args.command == "check":
            do_check(project)
        elif args.command == "scan":
            do_scan(project, args.commit)
        else:
            do_sheet(project, args.out or str(project.root / "build" / "icons" / "sheet"))
    except IconError as error:
        print(f"✗ {error}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
