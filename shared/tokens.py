@dataclass
class SwiftColor:
    rgb: tuple
    alpha: float = 1.0
    increased: object = None


@dataclass
class SwiftNumber:
    value: float
    kind: str


@dataclass
class SwiftMotion:
    kind: str
    curve: str | None = None
    duration: float | None = None
    response: float | None = None
    damping: float | None = None


@dataclass
class SwiftDecl:
    path: str
    family: str
    name: str
    annotation: str | None
    expr: str
    private: bool
    line: int


DECL = re.compile(r"^\s*(private\s+)?static\s+let\s+(\w+)\s*(?::\s*([\w.]+))?\s*=\s*(.+?)\s*$")
FAMILY = re.compile(r"^(?:\w+\s+)*(?:enum|struct)\s+(\w+)")
FIELD = re.compile(r"^\s*(?:private\s+)?(?:let|var)\s+(\w+)\s*:\s*([\w.]+)\s*$")
SYSTEM_COLORS = {"#FF3B30": "red"}
NUMBER = re.compile(r"0x[0-9A-Fa-f]+|-?\d+(?:\.\d+)?")
SWIFT_TYPES = {"CGFloat": "float", "Double": "double", "TimeInterval": "double", "Int": "int"}
SWIFT_CURVES = {"easeInOut": "ease_in_out", "easeOut": "ease_out", "easeIn": "ease_in"}


def strip_comment(line):
    out, quoted = [], False
    for index, char in enumerate(line):
        if char == '"':
            quoted = not quoted
        if not quoted and line.startswith("//", index):
            break
        out.append(char)
    return "".join(out)


def swift_decls(path, text, fields=None):
    """The `static let`s of a file's top-level enums and structs; a struct's stored fields go in `fields`."""
    decls = []
    depth = 0
    family = None
    for number_, raw in enumerate(text.splitlines(), start=1):
        line = strip_comment(raw)
        if depth == 0:
            match = FAMILY.match(line)
            if match:
                family = match.group(1)
        if depth == 1 and family:
            match = DECL.match(line)
            if match:
                private, name, annotation, expr = match.groups()
                decls.append(SwiftDecl(path, family, name, annotation, expr, bool(private), number_))
            match = FIELD.match(line)
            if match and fields is not None:
                fields[(family, match.group(1))] = match.group(2)
        depth += line.count("{") - line.count("}")
    return decls


def split_args(text):
    parts, depth, current = [], 0, []
    for char in text:
        if char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
        if char == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(char)
    if current:
        parts.append("".join(current).strip())
    return parts


def call_args(text):
    """The `label: value` pairs and the bare values of a call's arguments."""
    labelled, bare = {}, []
    for part in split_args(text):
        match = re.fullmatch(r"(\w+)\s*:\s*(.+)", part, re.S)
        if match:
            labelled[match.group(1)] = match.group(2).strip()
        else:
            bare.append(part)
    return labelled, bare


class SwiftReader:
    """Reads a `static let` value in the few forms the design files use."""

    def __init__(self, decls, fields=None):
        self.decls = {(d.family, d.name): d for d in decls}
        self.fields = fields or {}
        self.cache = {}

    def value_of(self, decl):
        key = (decl.family, decl.name)
        if key not in self.cache:
            self.cache[key] = None
            self.cache[key] = self.typed(self.evaluate(decl.expr, decl.family), decl.annotation)
        return self.cache[key]

    @staticmethod
    def typed(value, annotation):
        if isinstance(value, SwiftNumber) and annotation:
            return SwiftNumber(value.value, SWIFT_TYPES.get(annotation, annotation))
        return value

    def lookup(self, name, family):
        family_name, _, member = name.rpartition(".")
        decl = self.decls.get((family_name or family, member))
        if decl is None:
            raise TokenError(f"cannot read '{name}'")
        return self.value_of(decl)

    def number(self, text, family):
        value = self.evaluate(text, family)
        if not isinstance(value, SwiftNumber):
            raise TokenError(f"'{text}' is not a number")
        return value.value

    def evaluate(self, expr, family):
        expr = expr.strip()
        if re.fullmatch(r"-?\d+", expr):
            return SwiftNumber(float(expr), "int")
        if re.fullmatch(r"-?\d+\.\d+", expr):
            return SwiftNumber(float(expr), "double")
        match = re.fullmatch(r"(-?\d+(?:\.\d+)?)\s*/\s*(\d+(?:\.\d+)?)", expr)
        if match:
            return SwiftNumber(float(match.group(1)) / float(match.group(2)), "double")
        match = re.fullmatch(r"(.+)\.opacity\(([^()]+)\)", expr, re.S)
        if match:
            color = self.evaluate(match.group(1), family)
            if not isinstance(color, SwiftColor):
                raise TokenError(f"'{expr}' is not a colour")
            return SwiftColor(color.rgb, color.alpha * self.number(match.group(2), family))
        match = re.fullmatch(r'(?:SwiftUI\.)?Color\("#?([0-9A-Fa-f]{6})"\)', expr)
        if match:
            hex_value = match.group(1)
            return SwiftColor(tuple(int(hex_value[i : i + 2], 16) for i in (0, 2, 4)))
        match = re.fullmatch(r"(?:(?:SwiftUI\.)?Color)?\.(white|black|clear)", expr)
        if match:
            return {
                "white": SwiftColor((255, 255, 255)),
                "black": SwiftColor((0, 0, 0)),
                "clear": SwiftColor((0, 0, 0), 0.0),
            }[match.group(1)]
        match = re.fullmatch(r"(?:SwiftUI\.)?Color\((.+)\)", expr, re.S)
        if match:
            labelled, _ = call_args(match.group(1))
            if {"red", "green", "blue"} <= set(labelled):
                rgb = tuple(round(self.number(labelled[c], family) * 255) for c in ("red", "green", "blue"))
                return SwiftColor(rgb)
        match = re.fullmatch(r"AdaptiveColor\.contrast\((.+)\)", expr, re.S)
        if match:
            labelled, bare = call_args(match.group(1))
            standard = self.evaluate(bare[0], family)
            return SwiftColor(standard.rgb, standard.alpha, self.evaluate(labelled["increased"], family))
        match = re.fullmatch(r"(?:Animation)?\.(easeInOut|easeOut|easeIn)\(duration:\s*(.+)\)", expr)
        if match:
            return SwiftMotion("curve", SWIFT_CURVES[match.group(1)], self.number(match.group(2), family))
        match = re.fullmatch(r"(?:Animation)?\.(spring|interactiveSpring)\((.+)\)", expr)
        if match:
            labelled, _ = call_args(match.group(2))
            kind = "spring" if match.group(1) == "spring" else "interactive_spring"
            damping = self.number(labelled["dampingFraction"], family) if "dampingFraction" in labelled else None
            return SwiftMotion(kind, response=self.number(labelled["response"], family), damping=damping)
        match = re.fullmatch(r"(?:Animation)?\.smooth\(duration:\s*(.+)\)", expr)
        if match:
            return SwiftMotion("smooth", duration=self.number(match.group(1), family))
        match = re.fullmatch(r"(Self|[A-Z]\w*)\((.+)\)", expr, re.S)
        if match:
            owner = family if match.group(1) == "Self" else match.group(1)
            labelled, bare = call_args(match.group(2))
            if labelled and not bare:
                return {
                    label: self.typed(self.evaluate(value, family), self.fields.get((owner, label)))
                    for label, value in labelled.items()
                }
        if re.fullmatch(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?", expr):
            return self.lookup(expr, family)
        raise TokenError(f"cannot read '{expr}'")


def same_number(a, b):
    return math.isclose(float(a), float(b), rel_tol=1e-9, abs_tol=1e-9)


def motion_text(motion):
    if not isinstance(motion, SwiftMotion):
        return str(motion)
    parts = [f"{key} {value:g}" if isinstance(value, float) else f"{key} {value}" for key, value in vars(motion).items()]
    return ", ".join(part for part in parts if not part.endswith(" None"))


def describe(color):
    text = "#%02X%02X%02X" % tuple(color.rgb)
    return text if same_number(color.alpha, 1) else f"{text} at {color.alpha:g}"


def parse_source(source):
    if not isinstance(source, str):
        return None
    match = SOURCE_PATTERN.fullmatch(source.strip())
    if match is None:
        return None
    first = int(match.group(2))
    last = int(match.group(3) or first)
    return match.group(1), first, last


class Gate:
    def __init__(self, root, repo):
        self.root = root
        self.repo = repo
        self.files = {}
        self.problems = []

    def show(self, commit, path):
        key = (commit, path)
        if key not in self.files:
            result = subprocess.run(
                ["git", "-C", str(self.repo), "show", f"{commit}:{path}"],
                capture_output=True,
                text=True,
            )
            if result.returncode != 0:
                raise TokenError(f"cannot read {path} at {commit}: {result.stderr.strip()}")
            self.files[key] = result.stdout
        return self.files[key]

    def problem(self, where, text):
        self.problems.append(f"{where}: {text}")

    def toml_color(self, shade, path):
        if shade.hex is not None:
            rgb, alpha = tuple(int(shade.hex[i : i + 2], 16) for i in (1, 3, 5)), 1.0
        else:
            target = self.toml_value(find(self.root, shade.resolved))
            rgb, alpha = target.rgb, target.alpha
        if shade.alpha is not None:
            alpha *= shade.alpha
        return SwiftColor(rgb, alpha)

    def toml_value(self, item):
        """The TOML entry in the shape the Swift reader gives."""
        if isinstance(item, Number):
            return SwiftNumber(item.value, item.kind)
        if isinstance(item, Ref):
            return self.toml_value(find(self.root, item.resolved))
        if isinstance(item, ColorToken):
            color = self.toml_color(item.shade, item.where)
            if item.increased is not None:
                color.increased = self.toml_color(item.increased, item.where)
            return color
        if isinstance(item, Motion):
            if item.kind == "curve":
                return SwiftMotion("curve", item.curve, item.duration.value)
            if item.kind == "smooth":
                return SwiftMotion("smooth", duration=item.duration.value)
            return SwiftMotion(item.kind, response=item.response, damping=item.damping)
        if isinstance(item, Group):
            return {camel(child.name): self.toml_value(child) for child in item.items}
        return None

    def differ(self, toml, swift):
        """How two values differ, or None when they are the same."""
        if isinstance(swift, SwiftNumber):
            if not isinstance(toml, SwiftNumber):
                return "Swift has a number"
            if not same_number(toml.value, swift.value):
                return f"TOML {toml.value:g}, Swift {swift.value:g}"
            if toml.kind != swift.kind:
                return f"TOML is a {toml.kind}, Swift a {swift.kind}"
            return None
        if isinstance(swift, SwiftColor):
            if not isinstance(toml, SwiftColor):
                return "Swift has a colour"
            if tuple(toml.rgb) != tuple(swift.rgb) or not same_number(toml.alpha, swift.alpha):
                return f"TOML {describe(toml)}, Swift {describe(swift)}"
            if (toml.increased is None) != (swift.increased is None):
                return "only one side has an Increase Contrast colour"
            if swift.increased is not None:
                inner = self.differ(toml.increased, swift.increased)
                return f"increased: {inner}" if inner else None
            return None
        if isinstance(swift, SwiftMotion):
            return None if toml == swift else f"TOML {motion_text(toml)}, Swift {motion_text(swift)}"
        if isinstance(swift, dict):
            if not isinstance(toml, dict) or set(toml) != set(swift):
                return f"TOML fields {sorted(toml) if isinstance(toml, dict) else toml}, Swift fields {sorted(swift)}"
            for key in swift:
                inner = self.differ(toml[key], swift[key])
                if inner:
                    return f"{key}: {inner}"
            return None
        return f"cannot compare {swift!r}"

    def commit(self):
        commits = {item.ios_commit for _, _, item in walk(self.root) if item.ios_commit}
        if len(commits) != 1:
            raise TokenError(f"the token files name {len(commits)} iOS commits; they need one")
        return commits.pop()

    def design_files(self):
        """Every `static let` of the two design files is a token, and the other way round."""
        commit = self.commit()
        fields = {}
        decls = [decl for path in DESIGN_FILES for decl in swift_decls(path, self.show(commit, path), fields)]
        reader = SwiftReader(decls, fields)
        tokens = {}
        for family in self.root.items:
            if isinstance(family, Group):
                for item in family.items:
                    tokens[(camel(family.name, upper=True), camel(item.name))] = item
        for decl in decls:
            if decl.private:
                continue
            where = f"{decl.path}:{decl.line} {decl.family}.{decl.name}"
            item = tokens.pop((decl.family, decl.name), None)
            if item is None:
                self.problem(where, "no token in the TOML")
                continue
            try:
                swift = reader.value_of(decl)
            except TokenError as error:
                self.problem(where, str(error))
                continue
            difference = self.differ(self.toml_value(item), swift)
            if difference:
                self.problem(where, difference)
            if parse_source(item.source) != (decl.path, decl.line, decl.line):
                self.problem(item.where, f"source should be {decl.path}:{decl.line}")
        for item in tokens.values():
            source = parse_source(item.source)
            if source is not None and source[0] in DESIGN_FILES:
                self.problem(item.where, f"{source[0]} has no such token")
        return reader

    def sources(self, reader):
        """Every other source line still holds its token's value."""
        for _, _, item in walk(self.root):
            if item.platform == "android":
                continue
            source = parse_source(item.source)
            if source is None or source[0] in DESIGN_FILES:
                continue
            path, first, last = source
            try:
                lines = self.show(item.ios_commit, path).splitlines()
            except TokenError as error:
                self.problem(item.where, str(error))
                continue
            if last > len(lines):
                self.problem(item.where, f"{path} has {len(lines)} lines")
                continue
            text = "\n".join(strip_comment(line) for line in lines[first - 1 : last])
            at = f"{path}:{first}" + (f"-{last}" if last != first else "")
            match = DECL.match(text) if first == last else None
            if match and isinstance(item, (Number, Ref, ColorToken, Motion)):
                difference = self.static_line(item, match, reader)
                if difference is not None:
                    if difference:
                        self.problem(item.where, f"{at}: {difference}")
                    continue
            missing = self.missing(item, text)
            if missing:
                self.problem(item.where, f"{at} lacks {', '.join(missing)}")

    def static_line(self, item, match, reader):
        """Compares a token with the `static let` on its line; None when the line can't be read."""
        _, _, annotation, expr = match.groups()
        try:
            swift = reader.typed(reader.evaluate(expr, None), annotation)
        except TokenError:
            return None
        toml = self.toml_value(item)
        if isinstance(swift, dict) != isinstance(toml, dict):
            return None
        if isinstance(swift, SwiftNumber) and isinstance(toml, SwiftNumber):
            return "" if same_number(toml.value, swift.value) else f"has {swift.value:g}, TOML {toml.value:g}"
        return self.differ(toml, swift) or ""

    def missing(self, item, text):
        """What of the token's value the source text doesn't show."""
        numbers = [float(int(n, 16)) if n.startswith("0x") else float(n) for n in NUMBER.findall(text)]
        if re.search(r"\bunit\b", text):
            numbers.append(1.0)
        lower = text.lower()

        def has(value):
            return any(same_number(value, n) for n in numbers)

        wanted = []
        if isinstance(item, Number):
            wanted = [("number", item.value)]
        elif isinstance(item, Ref):
            target = camel(item.target.rpartition(".")[2])
            return [] if target in text else [target]
        elif isinstance(item, ColorToken):
            wanted = [("shade", item.shade)]
            if item.shade.alpha is not None:
                wanted.append(("number", item.shade.alpha))
        elif isinstance(item, Shadow):
            for layer in item.layers + item.inner:
                wanted += [("number", layer.alpha), ("number", layer.radius)]
                wanted += [("number", value) for value in (layer.x, layer.y) if value]
                if layer.color.startswith("#"):
                    wanted.append(("color", layer.color))
        elif isinstance(item, Motion):
            parts = [item.duration, item.delay, item.stagger]
            wanted = [("number", part.value) for part in parts if part is not None]
            wanted += [("number", part) for part in (item.response, item.damping) if part is not None]
        elif isinstance(item, Curve):
            wanted = [("number", point) for point in item.points]
        elif isinstance(item, Cap):
            wanted = [("text", item.size)]
        elif isinstance(item, Text):
            wanted = [("text", item.value)]
        elif isinstance(item, Texts):
            wanted = [("text", value) for value in item.values]
        elif isinstance(item, Group):
            for child in item.items:
                if child.source is None and isinstance(child, Number):
                    wanted.append(("number", child.value))
                elif child.source is None and isinstance(child, Text):
                    wanted.append(("text", child.value))
        absent = []
        for kind, value in wanted:
            if kind == "number" and not has(value):
                absent.append(f"{value:g}")
            elif kind == "text" and value not in text:
                absent.append(f"'{value}'")
            elif kind == "shade" and not shows_color(value.hex or value.ref, lower):
                absent.append(value.hex or value.ref)
            elif kind == "color" and not shows_color(value, lower):
                absent.append(value)
        return absent

    def run(self):
        reader = self.design_files()
        self.sources(reader)
        return self.problems


def shows_color(color, lower):
    """True when Swift text names a colour: its hex, white or black, or the token's name."""
    if color.startswith("#"):
        named = {"#000000": "black", "#FFFFFF": "white", **SYSTEM_COLORS}.get(color.upper())
        return color.lower()[1:] in lower or (named is not None and re.search(rf"\b{named}\b", lower) is not None)
    return camel(color.rpartition(".")[2]).lower() in lower


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="tokens.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--tokens",
        required=True,
        action="append",
        help="folder holding the token TOML files; a second one is laid over the first; a missing one is skipped",
    )
    parser.add_argument("--kotlin", help="Kotlin file to write (TurnTokens.kt)")
    parser.add_argument("--kotlin-package", default="com.sendaturn.app.view.generated", help="package of the Kotlin file")
    parser.add_argument("--swift", help="Swift file to write (TurnTokens.swift)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a file differs from what the TOML gives")
    parser.add_argument("--ios-gate", metavar="REPO", help="check the tokens against the iOS sources in this git repository")
    args = parser.parse_args(argv)
    if not args.kotlin and not args.swift and not args.ios_gate:
        parser.error("give --kotlin, --swift, --ios-gate or several")

    try:
        root = load(args.tokens)
    except TokenError as error:
        print(f"✗ tokens: {error}", file=sys.stderr)
        return 2

    if args.ios_gate:
        try:
            problems = Gate(root, args.ios_gate).run()
        except TokenError as error:
            print(f"✗ tokens: iOS gate: {error}", file=sys.stderr)
            return 2
        if problems:
            for problem in problems:
                print(f"✗ tokens: {problem}", file=sys.stderr)
            print(f"✗ tokens: {len(problems)} difference(s) from iOS", file=sys.stderr)
            return 1
        print("✓ tokens: the TOML matches iOS")

    outputs = []
    if args.kotlin:
        outputs.append((Path(args.kotlin), kotlin_source(root, args.kotlin_package)))
    if args.swift:
        outputs.append((Path(args.swift), swift_source(root)))

    stale = []
    for path, text in outputs:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"✓ tokens: wrote {path}")
    if stale:
        for path in stale:
            print(f"✗ tokens: {path} is stale; regenerate it from the TOML (./build.sh build does)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
