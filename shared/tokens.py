#!/usr/bin/env python3
"""Turn the shared look tokens (shared/tokens/*.toml) into Kotlin and Swift.

Every TOML file in the tokens folder is read in name order. Its top-level
tables become nested objects of TurnTokens (Kotlin) and nested enums of
TurnTokens (Swift); snake_case keys become lowerCamelCase names.

Entries are recognised by their keys:
  hex                   a colour: name + "Hex" string and a colour value
  layers                a shadow: a list of shadow layers
  points                a cubic bezier curve (x1, y1, x2, y2)
  dynamic_type_size     a text-size cap: Kotlin gets the font scale, Swift the size
  kind                  a motion: curve, spring, interactive_spring, smooth, keyframe_spring
  value                 one number, string or boolean, with metadata beside it
  ref                   another entry of the same table
  anything else         a nested group

A number is a Double when it has a `setting` (it is a stored setting's
default) or `type = "seconds"`, an Int with `type = "int"`, and a Float
(Kotlin) or CGFloat (Swift) otherwise. Springs convert as SwiftUI does:
stiffness = (2 pi / response)^2, dampingRatio = dampingFraction.

Files are written only when their content changes. With --check nothing is
written and the exit status is 1 when a written file is stale.
"""

import sys

if sys.version_info < (3, 11):
    sys.exit("✗ tokens: needs Python 3.11 or later, for tomllib")

import argparse
import math
import re
import struct
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

SCHEMA = 1
FILE_KEYS = {"schema", "ios_commit"}
META_KEYS = {"source", "role", "owner", "platform", "composited", "style", "ios_text_style", "system_locked"}
VALUE_KEYS = {"value", "setting", "type"}
COLOR_KEYS = {"hex", "setting", "setting_channels"}
MOTION_KEYS = {"kind", "curve", "duration", "response", "damping", "delay", "stagger", "preset"}
LAYER_KEYS = {"color", "alpha", "radius", "x", "y"}
PLATFORMS = {"android", "ios"}
NUMBER_TYPES = {"int", "seconds"}
ACRONYMS = {"ui", "id", "url", "xs", "xl"}
DEFAULT_DAMPING = 0.825
SPRING_PRESETS = {"snappy": (0.5, 0.15), "bouncy": (0.5, 0.3), "smooth": (0.5, 0.0)}
APPLE_CURVES = {"ease_in_out": "easeInOut", "ease_out": "easeOut", "ease_in": "easeIn"}
BODY_SIZE_BY_DYNAMIC_TYPE = {
    "xSmall": 14,
    "small": 15,
    "medium": 16,
    "large": 17,
    "xLarge": 19,
    "xxLarge": 21,
    "xxxLarge": 23,
}
MAX_LINE = 140
SWIFT_NAMED_COLORS = {"#000000": "SwiftUI.Color.black", "#FFFFFF": "SwiftUI.Color.white"}
GENERATED_NOTE = "Generated by toolkit/shared/tokens.py from shared/tokens/*.toml. Edit the TOML and rebuild."


class TokenError(Exception):
    pass


@dataclass
class Number:
    name: str
    value: float
    kind: str
    setting: str | None = None
    platform: str | None = None


@dataclass
class Text:
    name: str
    value: str
    platform: str | None = None


@dataclass
class Flag:
    name: str
    value: bool
    platform: str | None = None


@dataclass
class Ref:
    name: str
    target: str
    platform: str | None = None
    kind: str = "float"


@dataclass
class ColorToken:
    name: str
    hex: str
    setting: str | None
    channels: list[str] | None
    platform: str | None = None


@dataclass
class Layer:
    color: str
    alpha: float
    radius: float
    x: float
    y: float


@dataclass
class Shadow:
    name: str
    layers: list[Layer]
    platform: str | None = None


@dataclass
class Curve:
    name: str
    points: list[float]
    platform: str | None = None


@dataclass
class Cap:
    name: str
    size: str
    platform: str | None = None


@dataclass
class Motion:
    name: str
    kind: str
    curve: str | None = None
    duration: Number | None = None
    response: float | None = None
    damping: float | None = None
    delay: Number | None = None
    stagger: Number | None = None
    preset: str | None = None
    platform: str | None = None


@dataclass
class Group:
    name: str
    items: list = field(default_factory=list)
    platform: str | None = None


def camel(name, upper=False):
    parts = name.split("_")
    words = []
    for index, part in enumerate(parts):
        if index == 0 and not upper:
            words.append(part)
        elif part in ACRONYMS:
            words.append(part.upper())
        else:
            words.append(part[:1].upper() + part[1:])
    result = "".join(words)
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", result):
        raise TokenError(f"'{name}' does not make a valid name")
    return result


def check_keys(where, table, allowed):
    unknown = sorted(set(table) - allowed - META_KEYS)
    if unknown:
        raise TokenError(f"{where}: unknown key(s) {', '.join(unknown)}")


def platform_of(where, table):
    platform = table.get("platform")
    if platform is not None and platform not in PLATFORMS:
        raise TokenError(f"{where}: platform must be one of {', '.join(sorted(PLATFORMS))}")
    return platform


def is_number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def number(where, name, raw, kind=None):
    if isinstance(raw, dict):
        check_keys(where, raw, VALUE_KEYS)
        if "value" not in raw:
            raise TokenError(f"{where}: a value table needs 'value'")
        value = raw["value"]
        setting = raw.get("setting")
        declared = raw.get("type")
        if declared is not None and declared not in NUMBER_TYPES:
            raise TokenError(f"{where}: type must be one of {', '.join(sorted(NUMBER_TYPES))}")
        platform = platform_of(where, raw)
    else:
        value, setting, declared, platform = raw, None, None, None
    if not is_number(value):
        raise TokenError(f"{where}: '{value}' is not a number")
    if declared == "int":
        if not isinstance(value, int):
            raise TokenError(f"{where}: an int token needs a whole number")
        resolved = "int"
    elif declared == "seconds" or setting is not None or kind == "double":
        resolved = "double"
    else:
        resolved = "float"
    return Number(name, value, resolved, setting, platform)


def parse_value(where, name, raw):
    value = raw["value"]
    if isinstance(value, bool):
        check_keys(where, raw, {"value", "setting"})
        return Flag(name, value, platform_of(where, raw))
    if isinstance(value, str):
        check_keys(where, raw, {"value", "setting"})
        return Text(name, value, platform_of(where, raw))
    return number(where, name, raw)


def parse_color(where, name, raw):
    check_keys(where, raw, COLOR_KEYS)
    hex_value = raw["hex"]
    if not isinstance(hex_value, str) or not re.fullmatch(r"#[0-9A-Fa-f]{6}", hex_value):
        raise TokenError(f"{where}: hex must be '#' and six hex digits, without alpha")
    channels = raw.get("setting_channels")
    if channels is not None and (len(channels) != 3 or not all(isinstance(c, str) for c in channels)):
        raise TokenError(f"{where}: setting_channels names the red, green and blue settings")
    return ColorToken(name, hex_value.upper(), raw.get("setting"), channels, platform_of(where, raw))


def parse_shadow(where, name, raw):
    check_keys(where, raw, {"layers"})
    layers = []
    for index, layer in enumerate(raw["layers"]):
        spot = f"{where}.layers[{index}]"
        if not isinstance(layer, dict):
            raise TokenError(f"{spot}: a layer is a table")
        unknown = sorted(set(layer) - LAYER_KEYS)
        if unknown:
            raise TokenError(f"{spot}: unknown key(s) {', '.join(unknown)}")
        for required in ("color", "alpha", "radius"):
            if required not in layer:
                raise TokenError(f"{spot}: needs '{required}'")
        for key in ("alpha", "radius", "x", "y"):
            if key in layer and not is_number(layer[key]):
                raise TokenError(f"{spot}: {key} is not a number")
        layers.append(Layer(layer["color"], layer["alpha"], layer["radius"], layer.get("x", 0), layer.get("y", 0)))
    if not layers:
        raise TokenError(f"{where}: a shadow needs at least one layer")
    return Shadow(name, layers, platform_of(where, raw))


def parse_curve(where, name, raw):
    check_keys(where, raw, {"points"})
    points = raw["points"]
    if len(points) != 4 or not all(is_number(p) for p in points):
        raise TokenError(f"{where}: points are four numbers, x1 y1 x2 y2")
    return Curve(name, points, platform_of(where, raw))


def parse_cap(where, name, raw):
    check_keys(where, raw, {"dynamic_type_size"})
    size = raw["dynamic_type_size"]
    if size not in BODY_SIZE_BY_DYNAMIC_TYPE:
        raise TokenError(f"{where}: unknown dynamic type size '{size}'")
    return Cap(name, size, platform_of(where, raw))


def parse_motion(where, name, raw):
    check_keys(where, raw, MOTION_KEYS)
    kind = raw["kind"]
    required = {
        "curve": {"curve", "duration"},
        "spring": {"response"},
        "interactive_spring": {"response"},
        "smooth": {"duration"},
        "keyframe_spring": {"preset", "duration"},
    }
    if kind not in required:
        raise TokenError(f"{where}: unknown kind '{kind}'")
    missing = sorted(required[kind] - set(raw))
    if missing:
        raise TokenError(f"{where}: a {kind} needs {', '.join(missing)}")
    motion = Motion(name, kind, platform=platform_of(where, raw))
    if "curve" in raw:
        motion.curve = raw["curve"]
    if "duration" in raw:
        motion.duration = number(f"{where}.duration", "duration", raw["duration"], kind="double")
    if "delay" in raw:
        motion.delay = number(f"{where}.delay", "delay", raw["delay"], kind="double")
    if "stagger" in raw:
        motion.stagger = number(f"{where}.stagger", "stagger", raw["stagger"], kind="double")
    if "preset" in raw:
        if raw["preset"] not in SPRING_PRESETS:
            raise TokenError(f"{where}: unknown spring preset '{raw['preset']}'")
        motion.preset = raw["preset"]
    for key in ("response", "damping"):
        if key in raw:
            if not is_number(raw[key]) or raw[key] <= 0:
                raise TokenError(f"{where}: {key} is a positive number")
            setattr(motion, key, raw[key])
    if motion.duration is not None and motion.duration.value <= 0:
        raise TokenError(f"{where}: duration is a positive number")
    return motion


def parse_entry(where, name, raw):
    if not isinstance(raw, dict):
        if isinstance(raw, bool):
            return Flag(name, raw)
        if isinstance(raw, str):
            return Text(name, raw)
        return number(where, name, raw)
    for marker, parse in (
        ("hex", parse_color),
        ("layers", parse_shadow),
        ("points", parse_curve),
        ("dynamic_type_size", parse_cap),
        ("kind", parse_motion),
    ):
        if marker in raw:
            return parse(where, name, raw)
    if "value" in raw:
        return parse_value(where, name, raw)
    if "ref" in raw:
        check_keys(where, raw, {"ref"})
        return Ref(name, raw["ref"], platform_of(where, raw))
    group = Group(name, platform=platform_of(where, raw))
    for key, child in raw.items():
        if key in META_KEYS:
            continue
        group.items.append(parse_entry(f"{where}.{key}", key, child))
    return group


def load(tokens_dir):
    files = sorted(Path(tokens_dir).glob("*.toml"))
    if not files:
        raise TokenError(f"no *.toml files in {tokens_dir}")
    groups = {}
    for path in files:
        with path.open("rb") as handle:
            try:
                data = tomllib.load(handle)
            except tomllib.TOMLDecodeError as error:
                raise TokenError(f"{path.name}: {error}") from error
        if data.get("schema") != SCHEMA:
            raise TokenError(f"{path.name}: needs schema = {SCHEMA}")
        for key, raw in data.items():
            if key in FILE_KEYS:
                continue
            if not isinstance(raw, dict):
                raise TokenError(f"{path.name}: top-level '{key}' must be a table")
            if key in groups:
                raise TokenError(f"{path.name}: table '{key}' is also in another file")
            groups[key] = parse_entry(f"{path.name}:{key}", key, raw)
    root = Group("turn_tokens", list(groups.values()))
    validate(root)
    return root


def walk(group, path=()):
    for item in group.items:
        yield path, group, item
        if isinstance(item, Group):
            yield from walk(item, path + (item.name,))


def validate(root):
    colors = {}
    curves = {}
    for _, _, item in walk(root):
        if isinstance(item, ColorToken):
            colors[item.name] = item
        if isinstance(item, Curve):
            curves[item.name] = item
    for path, parent, item in walk(root):
        where = ".".join(path + (item.name,))
        names = [camel(other.name) for other in parent.items]
        if names.count(camel(item.name)) > 1:
            raise TokenError(f"{where}: two entries make the same name")
        if isinstance(item, Ref):
            target = next((other for other in parent.items if other.name == item.target), None)
            if not isinstance(target, Number):
                raise TokenError(f"{where}: ref '{item.target}' is not a number in the same table")
            item.kind = target.kind
        if isinstance(item, Shadow):
            for layer in item.layers:
                if not isinstance(layer.color, str):
                    raise TokenError(f"{where}: a layer colour is a hex or a colour name")
                if not layer.color.startswith("#") and layer.color not in colors:
                    raise TokenError(f"{where}: unknown colour '{layer.color}'")
                if layer.color.startswith("#") and not re.fullmatch(r"#[0-9A-Fa-f]{6}", layer.color):
                    raise TokenError(f"{where}: '{layer.color}' is not a six-digit hex")
        if isinstance(item, Motion) and item.curve is not None and item.curve not in curves:
            raise TokenError(f"{where}: unknown curve '{item.curve}'")


def settings_of(root):
    keys = []
    for _, _, item in walk(root):
        if isinstance(item, (Number, ColorToken)) and item.setting:
            keys.append(item.setting)
        if isinstance(item, ColorToken) and item.channels:
            keys.extend(item.channels)
        if isinstance(item, Motion):
            for part in (item.duration, item.delay, item.stagger):
                if part is not None and part.setting:
                    keys.append(part.setting)
    return keys


def check_settings(root, swift_root):
    sources = "\n".join(path.read_text(encoding="utf-8") for path in sorted(Path(swift_root).rglob("*.swift")))
    return [key for key in settings_of(root) if f'"{key}"' not in sources]


def stiffness(response):
    return (2 * math.pi / response) ** 2


def spring_parts(motion):
    if motion.kind == "smooth":
        return motion.duration.value, 1.0
    if motion.kind == "keyframe_spring":
        duration, bounce = SPRING_PRESETS[motion.preset]
        return duration, 1.0 - bounce
    return motion.response, motion.damping if motion.damping is not None else DEFAULT_DAMPING


def float32(value):
    target = struct.unpack("f", struct.pack("f", value))[0]
    for digits in range(1, 10):
        text = f"{target:.{digits}g}"
        if struct.unpack("f", struct.pack("f", float(text)))[0] == target:
            break
    if "e" in text:
        text = f"{target:.9f}".rstrip("0").rstrip(".")
    return text


def kotlin_float(value):
    text = float32(value)
    return f"{text}f"


def kotlin_double(value):
    return repr(float(value))


def swift_number(value):
    value = float(value)
    return str(int(value)) if value.is_integer() else repr(value)


def millis(seconds):
    return int(round(seconds * 1000))


def kotlin_dp(value):
    value = float(value)
    text = str(int(value)) if value.is_integer() else repr(value)
    return f"({text}).dp" if value < 0 else f"{text}.dp"


def included(item, platform):
    return item.platform is None or item.platform == platform


class KotlinWriter:
    def __init__(self, package):
        self.package = package
        self.lines = []
        self.imports = set()

    def render(self, root):
        body = []
        self.block(body, "object TurnTokens", root, 0)
        imports = sorted(i for i in self.imports if " as " not in i) + sorted(i for i in self.imports if " as " in i)
        head = [f"// {GENERATED_NOTE}", f"package {self.package}", ""]
        head += [f"import {i}" for i in imports]
        return "\n".join(head + [""] + body) + "\n"

    def block(self, out, header, group, depth):
        pad = "    " * depth
        out.append(f"{pad}{header} {{")
        previous = None
        for item in group.items:
            if not included(item, "android"):
                continue
            lines, shape = self.member(item, depth + 1)
            if not lines:
                continue
            if previous is not None and (shape != "property" or previous != "property"):
                out.append("")
            out.extend(lines)
            previous = shape
        out.append(f"{pad}}}")

    def member(self, item, depth):
        pad = "    " * depth
        name = camel(item.name)
        if isinstance(item, Group):
            out = []
            self.block(out, f"object {camel(item.name, upper=True)}", item, depth)
            return out, "object"
        if isinstance(item, Number):
            return [f"{pad}val {name}: {self.number_type(item)} = {self.number_literal(item)}"], "property"
        if isinstance(item, Text):
            return [f'{pad}val {name}: String = "{item.value}"'], "property"
        if isinstance(item, Flag):
            return [f"{pad}val {name}: Boolean = {'true' if item.value else 'false'}"], "property"
        if isinstance(item, Ref):
            return [f"{pad}val {name}: {self.number_type(item)} = {camel(item.target)}"], "property"
        if isinstance(item, ColorToken):
            self.imports.add("androidx.compose.ui.graphics.Color as ComposeColor")
            out = [
                f'{pad}val {name}Hex: String = "{item.hex}"',
                f"{pad}val {name}: ComposeColor = ComposeColor(0xFF{item.hex[1:]})",
            ]
            if item.channels:
                for channel, offset in (("Red", 1), ("Green", 3), ("Blue", 5)):
                    level = int(item.hex[offset : offset + 2], 16) / 255
                    out.append(f"{pad}val {name}{channel}: Double = {kotlin_double(level)}")
            return out, "property"
        if isinstance(item, Shadow):
            self.imports.update({"androidx.compose.ui.unit.dp", "com.sendaturn.app.view.ShadowLayer"})
            out = [f"{pad}val {name}: List<ShadowLayer> =", f"{pad}    listOf("]
            for layer in item.layers:
                args = [f"color = {self.layer_color(layer)}", f"radius = {kotlin_dp(layer.radius)}"]
                if layer.x:
                    args.append(f"x = {kotlin_dp(layer.x)}")
                if layer.y:
                    args.append(f"y = {kotlin_dp(layer.y)}")
                out.append(f"{pad}        ShadowLayer({', '.join(args)}),")
            out.append(f"{pad}    )")
            return out, "property"
        if isinstance(item, Curve):
            self.imports.add("androidx.compose.animation.core.CubicBezierEasing")
            points = ", ".join(kotlin_float(p) for p in item.points)
            return [f"{pad}val {name}: CubicBezierEasing = CubicBezierEasing({points})"], "property"
        if isinstance(item, Cap):
            scale = BODY_SIZE_BY_DYNAMIC_TYPE[item.size] / BODY_SIZE_BY_DYNAMIC_TYPE["large"]
            return [f"{pad}val {name}: Float = {kotlin_float(scale)}"], "property"
        if isinstance(item, Motion):
            return self.motion(item, pad, name), "function"
        raise TokenError(f"cannot write {item!r}")

    def motion(self, item, pad, name):
        out = []
        if item.kind == "curve":
            self.imports.update({"androidx.compose.animation.core.TweenSpec", "androidx.compose.animation.core.tween"})
            out.append(f"{pad}val {name}Duration: Double = {kotlin_double(item.duration.value)}")
            out.append(f"{pad}val {name}DurationMillis: Int = {millis(item.duration.value)}")
        else:
            self.imports.update({"androidx.compose.animation.core.SpringSpec", "androidx.compose.animation.core.spring"})
            response, damping = spring_parts(item)
            out.append(f"{pad}val {name}Response: Double = {kotlin_double(response)}")
            out.append(f"{pad}val {name}DampingRatio: Float = {kotlin_float(damping)}")
            out.append(f"{pad}val {name}Stiffness: Float = {kotlin_float(stiffness(response))}")
            if item.kind == "keyframe_spring":
                out.append(f"{pad}val {name}Duration: Double = {kotlin_double(item.duration.value)}")
                out.append(f"{pad}val {name}DurationMillis: Int = {millis(item.duration.value)}")
        for label, part in (("Delay", item.delay), ("Stagger", item.stagger)):
            if part is not None:
                out.append(f"{pad}val {name}{label}: Double = {kotlin_double(part.value)}")
                out.append(f"{pad}val {name}{label}Millis: Long = {millis(part.value)}L")
        out.append("")
        if item.kind == "curve":
            easing = f"Curve.{camel(item.curve)}"
            line = f"{pad}fun <T> {name}(): TweenSpec<T> = tween(durationMillis = {name}DurationMillis, easing = {easing})"
            if len(line) <= MAX_LINE:
                out.append(line)
            else:
                out.append(f"{pad}fun <T> {name}(): TweenSpec<T> =")
                out.append(f"{pad}    tween(")
                out.append(f"{pad}        durationMillis = {name}DurationMillis,")
                out.append(f"{pad}        easing = {easing},")
                out.append(f"{pad}    )")
        else:
            out.append(f"{pad}fun <T> {name}(visibilityThreshold: T? = null): SpringSpec<T> =")
            out.append(f"{pad}    spring(")
            out.append(f"{pad}        dampingRatio = {name}DampingRatio,")
            out.append(f"{pad}        stiffness = {name}Stiffness,")
            out.append(f"{pad}        visibilityThreshold = visibilityThreshold,")
            out.append(f"{pad}    )")
        return out

    def number_type(self, item):
        return {"int": "Int", "double": "Double", "float": "Float"}[item.kind]

    def number_literal(self, item):
        if item.kind == "int":
            return str(int(item.value))
        if item.kind == "double":
            return kotlin_double(item.value)
        return kotlin_float(item.value)

    def layer_color(self, layer):
        base = f"ComposeColor(0xFF{layer.color[1:].upper()})" if layer.color.startswith("#") else f"Color.{camel(layer.color)}"
        if layer.color.startswith("#"):
            self.imports.add("androidx.compose.ui.graphics.Color as ComposeColor")
        return f"{base}.copy(alpha = {kotlin_float(layer.alpha)})"


class SwiftWriter:
    def render(self, root):
        body = []
        self.uses_shadow = any(isinstance(i, Shadow) and included(i, "ios") for _, _, i in walk(root))
        self.uses_curve = any(isinstance(i, Curve) and included(i, "ios") for _, _, i in walk(root))
        body.append("enum TurnTokens {")
        support = []
        if self.uses_shadow:
            support.append(
                [
                    "    struct ShadowLayer {",
                    "        let color: SwiftUI.Color",
                    "        let radius: CGFloat",
                    "        let x: CGFloat",
                    "        let y: CGFloat",
                    "    }",
                ]
            )
        if self.uses_curve:
            support.append(
                [
                    "    struct CubicCurve {",
                    "        let x1: Double",
                    "        let y1: Double",
                    "        let x2: Double",
                    "        let y2: Double",
                    "    }",
                ]
            )
        for index, lines in enumerate(support):
            if index:
                body.append("")
            body.extend(lines)
        first = not support
        for item in root.items:
            if not included(item, "ios"):
                continue
            if not first:
                body.append("")
            first = False
            body.extend(self.member(item, 1))
        body.append("}")
        return "\n".join([f"// {GENERATED_NOTE}", "", "import SwiftUI", ""] + body) + "\n"

    def block(self, group, depth):
        pad = "    " * depth
        out = [f"{pad}enum {camel(group.name, upper=True)} {{"]
        previous = None
        for item in group.items:
            if not included(item, "ios"):
                continue
            lines = self.member(item, depth + 1)
            shape = "group" if isinstance(item, Group) else "property"
            if previous is not None and (shape == "group" or previous == "group"):
                out.append("")
            out.extend(lines)
            previous = shape
        out.append(f"{pad}}}")
        return out

    def member(self, item, depth):
        pad = "    " * depth
        name = camel(item.name)
        if isinstance(item, Group):
            return self.block(item, depth)
        if isinstance(item, Number):
            swift_type = {"int": "Int", "double": "Double", "float": "CGFloat"}[item.kind]
            literal = str(int(item.value)) if item.kind == "int" else swift_number(item.value)
            return [f"{pad}static let {name}: {swift_type} = {literal}"]
        if isinstance(item, Text):
            return [f'{pad}static let {name} = "{item.value}"']
        if isinstance(item, Flag):
            return [f"{pad}static let {name} = {'true' if item.value else 'false'}"]
        if isinstance(item, Ref):
            swift_type = {"int": "Int", "double": "Double", "float": "CGFloat"}[item.kind]
            return [f"{pad}static let {name}: {swift_type} = {camel(item.target)}"]
        if isinstance(item, ColorToken):
            out = [f'{pad}static let {name}Hex = "{item.hex}"', f"{pad}static let {name} = SwiftUI.Color({name}Hex)"]
            if item.channels:
                for channel, offset in (("Red", 1), ("Green", 3), ("Blue", 5)):
                    level = int(item.hex[offset : offset + 2], 16) / 255
                    out.append(f"{pad}static let {name}{channel}: Double = {repr(level)}")
            return out
        if isinstance(item, Shadow):
            out = [f"{pad}static let {name}: [ShadowLayer] = ["]
            for layer in item.layers:
                color = self.layer_color(layer)
                out.append(
                    f"{pad}    ShadowLayer(color: {color}.opacity({swift_number(layer.alpha)}), radius: {swift_number(layer.radius)}, "
                    f"x: {swift_number(layer.x)}, y: {swift_number(layer.y)}),"
                )
            out.append(f"{pad}]")
            return out
        if isinstance(item, Curve):
            x1, y1, x2, y2 = (swift_number(p) for p in item.points)
            return [f"{pad}static let {name} = CubicCurve(x1: {x1}, y1: {y1}, x2: {x2}, y2: {y2})"]
        if isinstance(item, Cap):
            return [f"{pad}static let {name} = DynamicTypeSize.{item.size}"]
        if isinstance(item, Motion):
            return self.motion(item, pad, name)
        raise TokenError(f"cannot write {item!r}")

    def layer_color(self, layer):
        if not layer.color.startswith("#"):
            return f"Color.{camel(layer.color)}"
        return SWIFT_NAMED_COLORS.get(layer.color.upper(), f'SwiftUI.Color("{layer.color.upper()}")')

    def motion(self, item, pad, name):
        out = []
        delay = item.delay is not None and item.stagger is None
        suffix = f".delay({swift_number(item.delay.value)})" if delay else ""
        if item.kind == "curve":
            seconds = swift_number(item.duration.value)
            if item.curve in APPLE_CURVES:
                animation = f"Animation.{APPLE_CURVES[item.curve]}(duration: {seconds})"
            else:
                curve = self.curves[item.curve]
                x1, y1, x2, y2 = (swift_number(p) for p in curve.points)
                animation = f"Animation.timingCurve({x1}, {y1}, {x2}, {y2}, duration: {seconds})"
            out.append(f"{pad}static let {name} = {animation}{suffix}")
        elif item.kind == "smooth":
            out.append(f"{pad}static let {name} = Animation.smooth(duration: {swift_number(item.duration.value)}){suffix}")
        elif item.kind == "keyframe_spring":
            out.append(f"{pad}static let {name}: Spring = .{item.preset}")
            out.append(f"{pad}static let {name}Duration: TimeInterval = {swift_number(item.duration.value)}")
        else:
            function = "interactiveSpring" if item.kind == "interactive_spring" else "spring"
            args = f"response: {swift_number(item.response)}"
            if item.damping is not None:
                args += f", dampingFraction: {swift_number(item.damping)}"
            out.append(f"{pad}static let {name} = Animation.{function}({args}){suffix}")
        if item.kind == "curve" and item.duration.setting:
            out.append(f"{pad}static let {name}Duration: Double = {swift_number(item.duration.value)}")
        for label, part in (("Delay", item.delay), ("Stagger", item.stagger)):
            if part is not None:
                out.append(f"{pad}static let {name}{label}: TimeInterval = {swift_number(part.value)}")
        return out


def kotlin_source(root, package):
    return KotlinWriter(package).render(root)


def swift_source(root):
    writer = SwiftWriter()
    writer.curves = {item.name: item for _, _, item in walk(root) if isinstance(item, Curve)}
    return writer.render(root)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="tokens.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--tokens", required=True, help="folder holding the token TOML files")
    parser.add_argument("--kotlin", help="Kotlin file to write (TurnTokens.kt)")
    parser.add_argument("--kotlin-package", default="com.sendaturn.app.view.generated", help="package of the Kotlin file")
    parser.add_argument("--swift", help="Swift file to write (TurnTokens.swift)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a file differs from what the TOML gives")
    parser.add_argument("--settings-root", help="Swift sources that must mention every `setting` key in quotes")
    args = parser.parse_args(argv)
    if not args.kotlin and not args.swift:
        parser.error("give --kotlin, --swift or both")

    try:
        root = load(args.tokens)
    except TokenError as error:
        print(f"✗ tokens: {error}", file=sys.stderr)
        return 2

    if args.settings_root:
        missing = check_settings(root, args.settings_root)
        if missing:
            print(f"✗ tokens: settings no Swift source mentions: {', '.join(missing)}", file=sys.stderr)
            return 2

    outputs = []
    if args.kotlin:
        outputs.append((Path(args.kotlin), kotlin_source(root, args.kotlin_package)))
    if args.swift:
        outputs.append((Path(args.swift), swift_source(root)))

    stale = []
    for path, text in outputs:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"✓ tokens: wrote {path}")
    if stale:
        for path in stale:
            print(f"✗ tokens: {path} is stale; regenerate it from the TOML (./build.sh build does)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
