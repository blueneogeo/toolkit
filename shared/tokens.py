#!/usr/bin/env python3
"""Turn the shared look tokens (shared/tokens/*.toml) into Kotlin and Swift,
and check that iOS uses every token it is given.

Every TOML file in the tokens folders is read in name order. Its top-level
tables become nested objects of TurnTokens (Kotlin) and nested enums of
TurnTokens (Swift); snake_case keys become lowerCamelCase names, so
`palette.feed_paper` is `TurnTokens.Palette.feedPaper`. A top-level table may
be split over several files (`glass` holds colours in colors.toml and amounts
in effects.toml); a name defined twice fails. With two `--tokens` folders the
second one is laid over the first: a key there wins, a key only there is
added.

Entries are recognised by their keys:
  hex                   a colour, with `alpha` and `increased` (Increase Contrast)
  ref                   another entry: `name` in the same table, or `table.name`;
                        a colour ref may add `alpha` and `increased`
  layers                a shadow: a list of shadow layers, and `inner` for an inner shadow
  points                a cubic bezier curve (x1, y1, x2, y2)
  dynamic_type_size     a text-size cap: Kotlin gets the font scale, Swift the size
  kind                  a motion: curve, spring, interactive_spring, smooth, keyframe_spring
  value                 one number, string or boolean, with metadata beside it
  a list of strings     a list
  anything else         a nested group

A number is a Float (Kotlin) or CGFloat (Swift) unless it says
`type = "double"` or `type = "int"`. Springs convert as SwiftUI does:
stiffness = (2 pi / response)^2, dampingRatio = dampingFraction.

Files are written only when their content changes. With --check nothing is
written and the exit status is 1 when a written file is stale.

With --ios-usage every token the Swift file holds must be named, by its full
name (`TurnTokens.Radius.segmentedPill`), in a Swift file under the given
folder; the generated file is left out. A token with platform = "android" is
not in the Swift file. A token iOS reads in another way, an asset catalog or a
system material, says where with `ios_reads`. Exit status 1 lists every token
no Swift code uses.
"""

import sys

if sys.version_info < (3, 11):
    sys.exit("✗ tokens: needs Python 3.11 or later, for tomllib")

