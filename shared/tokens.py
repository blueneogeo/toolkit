def swift_names(group, path=(), platform="ios"):
    """The full Swift name of every token the Swift file holds, with the token."""
    for item in group.items:
        if not included(item, platform) or item.ios_reads:
            continue
        if isinstance(item, Group):
            yield from swift_names(item, path + (item.name,), platform)
            continue
        base = qualified(path + (item.name,))
        suffixes = [""]
        if isinstance(item, ColorToken) and item.increased is not None:
            suffixes.append("Increased")
        elif isinstance(item, Shadow) and item.inner:
            suffixes.append("Inner")
        elif isinstance(item, Motion):
            if item.kind == "keyframe_spring":
                suffixes.append("Duration")
        for suffix in suffixes:
            yield base + suffix, item


def unused_on_ios(root, folder):
    """Swift names no Swift file under the folder uses, the generated file left out."""
    texts = []
    for path in sorted(Path(folder).rglob("*.swift")):
        text = path.read_text(encoding="utf-8")
        if not text.startswith(f"// {GENERATED_NOTE}"):
            texts.append(text)
    code = "\n".join(texts)
    return [name for name, _ in swift_names(root) if not re.search(re.escape(name) + r"(?![A-Za-z0-9_])", code)]


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="tokens.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--tokens",
        required=True,
        action="append",
        help="folder holding the token TOML files; a second one is laid over the first; a missing one is skipped",
    )
    parser.add_argument("--kotlin", help="Kotlin file to write (TurnTokens.kt)")
    parser.add_argument("--kotlin-package", default="com.sendaturn.app.view.generated", help="package of the Kotlin file")
    parser.add_argument("--swift", help="Swift file to write (TurnTokens.swift)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when a file differs from what the TOML gives")
    parser.add_argument("--ios-usage", metavar="DIR", help="fail when a token of the Swift file is named in no Swift file under DIR")
    args = parser.parse_args(argv)
    if not args.kotlin and not args.swift and not args.ios_usage:
        parser.error("give --kotlin, --swift, --ios-usage or several")

    try:
        root = load(args.tokens)
    except TokenError as error:
        print(f"✗ tokens: {error}", file=sys.stderr)
        return 2

    outputs = []
    if args.kotlin:
        outputs.append((Path(args.kotlin), kotlin_source(root, args.kotlin_package)))
    if args.swift:
        outputs.append((Path(args.swift), swift_source(root)))

    stale = []
    for path, text in outputs:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"✓ tokens: wrote {path}")
    if stale:
        for path in stale:
            print(f"✗ tokens: {path} is stale; regenerate it from the TOML (./build.sh build does)", file=sys.stderr)
        return 1

    if args.ios_usage:
        unused = unused_on_ios(root, args.ios_usage)
        if unused:
            for name in unused:
                print(f"✗ tokens: no Swift code in {args.ios_usage} uses {name}", file=sys.stderr)
            print(f"✗ tokens: {len(unused)} token(s) unused on iOS; use them or mark them platform = \"android\"", file=sys.stderr)
            return 1
        print("✓ tokens: iOS uses every token")
    return 0


if __name__ == "__main__":
    sys.exit(main())
